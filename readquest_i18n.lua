function I18N.t(lang, key, ...)
    lang = I18N.resolveLang(lang)
    local dict = I18N.STRINGS[lang] or I18N.STRINGS.en
    local val = dict[key] or I18N.STRINGS.en[key] or key
    if select("#", ...) > 0 then
        local ok, res = pcall(string.format, val, ...)
        if ok then return res end
    end
    return val
end

function I18N.titleName(lang, idx)
    lang = I18N.resolveLang(lang)
    local arr = I18N.TITLES[lang] or I18N.TITLES.en
    return arr[idx] or arr[#arr] or "?"
end

function I18N.achInfo(lang, id)
    lang = I18N.resolveLang(lang)
    local item = I18N.ACHIEVEMENTS[id]
    if not item then return id, "" end
    local pair = item[lang] or item.en
    return pair[1], pair[2]
end

function I18N.bossPrefixList(lang)
    lang = I18N.resolveLang(lang)
    return I18N.BOSS_PREFIX[lang] or I18N.BOSS_PREFIX.en
end

function I18N.lootPool(lang, rarity)
    lang = I18N.resolveLang(lang)
    local tbl = I18N.LOOT[lang] or I18N.LOOT.en
    return tbl[rarity] or tbl.common
end

function I18N.rarityLabel(lang, rarity)
    lang = I18N.resolveLang(lang)
    local tbl = I18N.RARITY_LABEL[lang] or I18N.RARITY_LABEL.en
    return tbl[rarity] or rarity
end

function I18N.langOptionLabel(lang, code)
    if code == "auto" then
        lang = I18N.resolveLang(lang)
        return I18N.LANG_LABELS.auto[lang] or I18N.LANG_LABELS.auto.en
    end
    return I18N.LANG_LABELS[code] or code
end

