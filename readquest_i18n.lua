-- Tự động nhận diện ngôn ngữ từ KOReader (G_reader_settings)
function I18N.detectLang()
    local raw
    if G_reader_settings and type(G_reader_settings.readSetting) == "function" then
        raw = G_reader_settings:readSetting("language")
    end
    if not raw or raw == "" or raw == "C" then
        raw = os.getenv("LANG") or os.getenv("LC_ALL") or "en"
    end
    raw = tostring(raw):lower()
    if raw:find("^vi") then return "vi"
    elseif raw:find("^fr") then return "fr"
    elseif raw:find("^ja") then return "ja"
    elseif raw:find("^zh") then return "zh"
    elseif raw:find("^ko") then return "ko"
    else return "en" end
end

function I18N.resolveLang(cfg_lang)
    if not cfg_lang or cfg_lang == "auto" then
        return I18N.detectLang()
    end
    if I18N.STRINGS[cfg_lang] then
        return cfg_lang
    end
    return "en"
end

